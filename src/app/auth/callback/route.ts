import { NextResponse, type NextRequest } from "next/server";
import type { EmailOtpType } from "@supabase/supabase-js";
import { createClient } from "@/lib/supabase/server";
import { isSupabaseConfigured } from "@/lib/supabase/env";
import { safeNext } from "@/lib/utils/safe-redirect";

/**
 * Handles both Supabase email-link styles:
 *  - PKCE:        /auth/callback?code=...
 *  - Token hash:  /auth/callback?token_hash=...&type=signup|recovery|email
 * On failure it returns to /sign-in with an error flag (never loops).
 */
export async function GET(request: NextRequest) {
  const { searchParams, origin } = new URL(request.url);
  const code = searchParams.get("code");
  const tokenHash = searchParams.get("token_hash");
  const type = searchParams.get("type") as EmailOtpType | null;
  const next = safeNext(searchParams.get("next"));

  const failure = NextResponse.redirect(`${origin}/sign-in?error=link_invalid`);
  if (!isSupabaseConfigured()) return failure;

  const supabase = await createClient();

  if (code) {
    const { error } = await supabase.auth.exchangeCodeForSession(code);
    if (!error) return NextResponse.redirect(`${origin}${next}`);
  } else if (tokenHash && type) {
    const { error } = await supabase.auth.verifyOtp({ type, token_hash: tokenHash });
    if (!error) return NextResponse.redirect(`${origin}${next}`);
  }

  return failure;
}
